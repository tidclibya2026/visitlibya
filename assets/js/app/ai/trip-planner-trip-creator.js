export function flattenSuggestedItinerary(itinerary) {
  if (!Array.isArray(itinerary?.days)) {
    return [];
  }

  return itinerary.days.flatMap((day) => {
    const dayNumber = Number(day?.dayNumber);

    if (
      !Number.isSafeInteger(dayNumber) ||
      dayNumber < 1 ||
      !Array.isArray(day?.destinations)
    ) {
      return [];
    }

    return day.destinations
      .map((destination) => ({
        dayNumber,
        destination,
      }))
      .filter((entry) =>
        typeof entry.destination?.slug === "string" &&
        entry.destination.slug.trim(),
      );
  });
}


function normalizedSlug(value) {
  return String(value ?? "")
    .trim()
    .toLowerCase();
}


export async function resolveSuggestedDestinationIds(
  selectedDestinations,
  {
    listDestinationCatalogue,
  },
) {
  if (typeof listDestinationCatalogue !== "function") {
    throw new TypeError(
      "listDestinationCatalogue dependency is required",
    );
  }

  const requiredSlugs = new Set(
    selectedDestinations
      .map((destination) =>
        normalizedSlug(destination?.slug),
      )
      .filter(Boolean),
  );

  if (!requiredSlugs.size) {
    return new Map();
  }

  const resolved = new Map();

  let page = 1;
  let pageCount = Number.POSITIVE_INFINITY;

  while (
    page <= pageCount &&
    resolved.size < requiredSlugs.size
  ) {
    const payload =
      await listDestinationCatalogue(page);

    if (!payload || !Array.isArray(payload.items)) {
      throw new TypeError(
        "Invalid destination catalogue response",
      );
    }

    for (const item of payload.items) {
      const slug = normalizedSlug(item?.slug);
      const id = Number(item?.id);

      if (
        requiredSlugs.has(slug) &&
        Number.isSafeInteger(id) &&
        id > 0
      ) {
        resolved.set(slug, {
          id,
          slug,
        });
      }
    }

    const pages = Number(payload.pages);

    pageCount =
      Number.isSafeInteger(pages) && pages >= 1
        ? pages
        : page;

    page += 1;
  }

  if (resolved.size !== requiredSlugs.size) {
    const error = new Error(
      "Some suggested destinations are unavailable in the public catalogue",
    );

    error.code = "DESTINATION_UNAVAILABLE";
    throw error;
  }

  return resolved;
}


function canFallbackToLocalPlanner(error) {
  return [
    "API_UNAVAILABLE",
    "NETWORK_ERROR",
    "TIMEOUT",
    "SERVER_ERROR",
  ].includes(error?.code);
}

export async function createTripFromSuggestedItinerary({
  itinerary,
  locale = "en",
  apiEnabled,
  authenticatedUser,
  listDestinationCatalogue,
  createTrip,
  addTripItem,
  executeTripPlanner,
  plannerExecutionPayload,
}) {
  if (!apiEnabled) {
    const error = new Error("API_UNAVAILABLE");
    error.code = "API_UNAVAILABLE";
    throw error;
  }

  if (!authenticatedUser) {
    const error = new Error("AUTH_REQUIRED");
    error.code = "AUTH_REQUIRED";
    throw error;
  }

  let selected =
    flattenSuggestedItinerary(itinerary);

  if (!selected.length) {
    const error = new Error("EMPTY_ITINERARY");
    error.code = "EMPTY_ITINERARY";
    throw error;
  }

  if (
    typeof createTrip !== "function" ||
    typeof addTripItem !== "function"
  ) {
    throw new TypeError(
      "Trip API dependencies are required",
    );
  }

  let catalogue =
    await resolveSuggestedDestinationIds(
      selected.map((entry) => entry.destination),
      {
        listDestinationCatalogue,
      },
    );

  const trip = await createTrip({
    title:
      locale === "ar"
        ? "رحلتي المقترحة عبر Visit Libya"
        : "My Visit Libya Suggested Trip",

    description:
      locale === "ar"
        ? "برنامج رحلة تم إنشاؤه من مخطط الرحلات الذكي باستخدام بيانات وجهات Visit Libya."
        : "An itinerary generated by the Visit Libya smart trip planner using Visit Libya destination data.",

    start_date: null,
    end_date: null,
    status: "draft",
    visibility: "private",
  });

  if (
    !Number.isSafeInteger(Number(trip?.id)) ||
    Number(trip.id) < 1
  ) {
    throw new TypeError(
      "Invalid trip creation response",
    );
  }

  let authoritativeItinerary = itinerary;

  if (
    typeof executeTripPlanner === "function" &&
    typeof plannerExecutionPayload === "function"
  ) {
    try {
      const execution = await executeTripPlanner(
        trip.id,
        plannerExecutionPayload(itinerary),
      );

      if (
        execution?.result &&
        Array.isArray(execution.result.days)
      ) {
        authoritativeItinerary = execution.result;
      }
    } catch (error) {
      if (!canFallbackToLocalPlanner(error)) {
        throw error;
      }
    }
  }

  selected =
    flattenSuggestedItinerary(authoritativeItinerary);

  catalogue =
    await resolveSuggestedDestinationIds(
      selected.map((entry) => entry.destination),
      {
        listDestinationCatalogue,
      },
    );

  for (
    let index = 0;
    index < selected.length;
    index += 1
  ) {
    const entry = selected[index];

    const slug =
      normalizedSlug(entry.destination.slug);

    const identity = catalogue.get(slug);

    await addTripItem(trip.id, {
      destination_id: identity.id,
      day_number: entry.dayNumber,
      sort_order: index + 1,
      notes: null,
    });
  }

  return trip;
}
